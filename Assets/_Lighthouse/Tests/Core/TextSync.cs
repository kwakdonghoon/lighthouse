            rawJson = Regex.Replace(rawJson, "관리인이 부두에서 낚시로 ([^\\\\\"]+?)(?:을|를) 낚았어요", m => "관리인이 부두 근처에서 " + GameContext.FixJosa(m.Groups[1].Value + "{을/를}") + " 발견했어요");
            rawJson = Regex.Replace(rawJson, "먼 바다에서 커다란 고래가 물을 뿜고 ([^\\\\\"]+?)(?:을|를) 남기고 갔어요", m => "먼 바다에서 커다란 고래가 물을 뿜고 지나가자 " + GameContext.FixJosa(m.Groups[1].Value + "{이/가}") + " 밀려왔어요");
            return rawJson;
        }
