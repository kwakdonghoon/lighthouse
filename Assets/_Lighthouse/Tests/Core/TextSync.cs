        public static string Apply(string rawJson)
        {
            foreach (var p in Pairs) rawJson = rawJson.Replace(p[0], p[1]);
            // 선물 이름이 들어가는 일지 3문장: 골든에는 이름과 조사가 이미 풀려 있다(예: "옛 동전이"). 새 문장 틀로 바꾸되 조사는 새 틀({이/가}·{을/를})대로 다시 고른다.
