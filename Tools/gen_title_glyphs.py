# 타이틀 블록 글자 마스크 -> Render/TitleGlyphs.Generated.cs. 입력: Tools/golden/m4/out/title_glyphs.txt (ext_title.js 가 뽑음).
# 사용: python -I -X utf8 Tools/gen_title_glyphs.py
import os
base = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(base, 'golden', 'm4', 'out', 'title_glyphs.txt')
dst = os.path.join(base, '..', 'Assets', '_Lighthouse', 'Scripts', 'Render', 'TitleGlyphs.Generated.cs')
rows = []
for line in open(src, encoding='utf-8').read().split('\n'):
    if not line.strip():
        continue
    s, ch, bits = line.split(';')
    s = int(s)
    assert len(bits) == (s + 2) * (s + 2), (s, ch)
    bits += '0' * ((-len(bits)) % 4)
    hx = ''.join('%x' % int(bits[i:i + 4], 2) for i in range(0, len(bits), 4))
    rows.append((s, ch, hx))
out = ['// <auto-generated> Tools/gen_title_glyphs.py 가 만든 파일. 고치지 말 것.',
       '// 원본 HTML 타이틀 buildLetters 의 글자 마스크: 굵은 글꼴(골든을 뽑은 브라우저의 Noto Sans KR / 맑은 고딕)로 S px 로 그린 "등대지기" 네 글자의 알파 > 90 자리.',
       '// 글꼴 파일을 빌드에 넣지 않고 같은 모양을 재현하려고 미리 구워 둔 표다 (글자 크기 S = 16..28, 격자 (S+2)x(S+2), 위 행부터, 왼쪽부터, 비트 하나 = 도트 하나).',
       'namespace Lighthouse.Render', '{', '    public static partial class TitleGlyphs', '    {',
       '        static readonly string[] Table =', '        {']
for s, ch, hx in rows:
    out.append('            "%d;%s;%s",' % (s, ch, hx))
out += ['        };', '    }', '}', '']
open(dst, 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print(len(rows), 'glyph masks ->', dst)
